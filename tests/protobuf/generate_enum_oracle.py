schema = descriptor_pb2.FileDescriptorProto(name="enum.proto", package="example", syntax="proto3")
state = schema.enum_type.add(name="State")
for name, number in [("STATE_ZERO", 0), ("STATE_NEGATIVE", -1), ("STATE_READY", 1)]:
    state.value.add(name=name, number=number)
child = schema.message_type.add(name="EnumChild")
child.field.add(name="state", number=1, type=14, type_name=".example.State", label=1)
child.field.add(name="history", number=2, type=14, type_name=".example.State", label=3)
batch = schema.message_type.add(name="EnumBatch")
batch.field.add(name="state", number=1, type=14, type_name=".example.State", label=1)
batch.field.add(name="children", number=2, type=11, type_name=".example.EnumChild", label=3)
