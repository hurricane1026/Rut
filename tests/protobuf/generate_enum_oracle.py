def message_type(file):
    pool = descriptor_pool.DescriptorPool()
    pool.Add(file)
    return message_factory.GetMessageClass(pool.FindMessageTypeByName("example.EnumBatch"))


Message = message_type(schema)
message = Message(state=12345)
message.children.add(state=-1, history=[0, 1, -1, 12345, -2147483648, 2147483647])
message.children.add()
packed = message.SerializeToString(deterministic=True)
descriptor = descriptor_pb2.FileDescriptorSet()
descriptor.file.add().CopyFrom(schema)
# Rut currently emits unpacked repeated scalars; use the reference runtime to
# produce its expected output rather than duplicating Rut's encoder in Python.
schema.message_type[0].field[1].options.packed = False
Unpacked = message_type(schema)
canonical = Unpacked.FromString(packed).SerializeToString(deterministic=True)
assert Message.FromString(canonical) == message
oversized = Message()
oversized.children.add(history=[0] * 513)
fixtures = [("kEnumDescriptor", descriptor.SerializeToString()),
            ("kEnumPacked", packed), ("kEnumCanonical", canonical),
            ("kEnumOverElementLimit", oversized.SerializeToString())]
lines = [f"// Generated by generate_enum_oracle.py with protobuf {google.protobuf.__version__}."]
for name, data in fixtures:
    lines.append(f"inline constexpr unsigned char {name}[] = {{" + ", ".join(map(str, data)) + "};")
Path(__file__).with_name("enum_oracle.inc").write_text("\n".join(lines) + "\n")
