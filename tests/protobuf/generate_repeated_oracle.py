"""Regenerate with protobuf==6.33.5; optional development tool, never a build dependency."""
from pathlib import Path
from google.protobuf import descriptor_pb2, descriptor_pool, message_factory
import google.protobuf

schema = descriptor_pb2.FileDescriptorProto(name="repeated_oracle.proto", syntax="proto3")
child = schema.message_type.add(name="NestedChild")
for name, number, kind in [("text", 1, 9), ("id", 2, 5)]:
    child.field.add(name=name, number=number, type=kind, label=1)
parent = schema.message_type.add(name="RepeatedChild")
parent.field.add(name="children", number=1, type=11, type_name=".NestedChild", label=3)
pool = descriptor_pool.DescriptorPool()
pool.Add(schema)
Message = message_factory.GetMessageClass(pool.FindMessageTypeByName("RepeatedChild"))
message = Message()
message.children.add(text="雪\x00", id=-2147483648)
message.children.add()
message.children.add(text="last", id=2147483647)
wire = message.SerializeToString(deterministic=True)
# Duplicate singular fields are last-wins; unknown fields are dropped by Rut.
# Repeated empty children remain distinct. Validate normalization with Google's runtime.
noncanonical = bytes([10, 10, 16, 1, 10, 1, 97, 16, 2, 10, 1, 98, 10, 0, 24, 7])
normalized = Message.FromString(noncanonical)
normalized.DiscardUnknownFields()
assert normalized.children[0].text == "b" and normalized.children[0].id == 2
assert len(normalized.children) == 2
assert Message.FromString(wire) == message
lines = [f"// Generated by generate_repeated_oracle.py with protobuf {google.protobuf.__version__}."]
for name, data in [("kRepeatedOracle", wire), ("kRepeatedNoncanonical", noncanonical),
                   ("kRepeatedNormalized", normalized.SerializeToString(deterministic=True))]:
    lines.append(f"inline constexpr unsigned char {name}[] = {{" + ", ".join(map(str, data)) + "};")
Path(__file__).with_name("repeated_oracle.inc").write_text("\n".join(lines) + "\n")
