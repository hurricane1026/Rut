"""Optional protoc fixture generator: grpcio-tools==1.78.0, protobuf==6.33.5.

Run in an optional environment; neither package is a Rut build dependency.
"""
from pathlib import Path
import tempfile
from grpc_tools import protoc

root = Path(__file__).resolve().parent
with tempfile.TemporaryDirectory() as temporary:
    output = Path(temporary) / "strings.pb"
    result = protoc.main([
        "protoc", f"-I{root}", "--include_imports",
        f"--descriptor_set_out={output}", str(root / "strings.proto"),
    ])
    if result:
        raise SystemExit(result)
    wire = output.read_bytes()
(root / "strings_oracle.inc").write_text(
    "// Generated by generate_strings_oracle.py with libprotoc 31.1.\n"
    "inline constexpr unsigned char kStringsDescriptor[] = {" + ", ".join(map(str, wire)) + "};\n"
)
