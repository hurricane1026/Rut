"""Generate packed scalar reference bytes with Google protobuf 6.33.5."""
from pathlib import Path
from google.protobuf import descriptor_pb2, descriptor_pool, message_factory
kinds = [3, 5, 7, 8, 13, 14, 15, 16, 17, 18]
file = descriptor_pb2.FileDescriptorProto(name="packed.proto", syntax="proto3")
enum = file.enum_type.add(name="Choice")
enum.value.add(name="ZERO", number=0)
for kind in kinds:
    msg = file.message_type.add(name=f"M{kind}")
    field = msg.field.add(name="values", number=1, type=kind, label=3)
    field.options.packed = True
    if kind == 14:
        field.type_name = ".Choice"
pool = descriptor_pool.DescriptorPool()
pool.Add(file)
lines = ["// Generated by Google protobuf 6.33.5; packed numeric arrays."]
for kind in kinds:
    cls = message_factory.GetMessageClass(pool.FindMessageTypeByName(f"M{kind}"))
    values = [False, True, False] if kind == 8 else [1, 0, 150] if kind in [7, 13] else [-1, 0, 150]
    wire = cls(values=values).SerializeToString(deterministic=True)
    lines.append(f"inline constexpr unsigned char kPacked{kind}[] = {{" + ", ".join(map(str, wire)) + "};")
Path(__file__).with_name("packed_array_oracle.inc").write_text("\n".join(lines) + "\n")
