#!/usr/bin/env python3
"""Generate the grpc-status-details-bin oracle with protobuf 6.33.5."""
import base64
import google.protobuf
from google.protobuf import any_pb2, descriptor_pb2, descriptor_pool, message_factory, wrappers_pb2

assert google.protobuf.__version__ == "6.33.5", google.protobuf.__version__
fd = descriptor_pb2.FileDescriptorProto(name='google/rpc/status.proto', package='google.rpc', syntax='proto3')
fd.dependency.append('google/protobuf/any.proto')
msg = fd.message_type.add(name='Status')
for name, number, typ, label in [('code', 1, 5, 1), ('message', 2, 9, 1), ('details', 3, 11, 3)]:
    field = msg.field.add(name=name, number=number, type=typ, label=label)
    if name == 'details': field.type_name = '.google.protobuf.Any'
pool = descriptor_pool.Default()
pool.Add(fd)
Status = message_factory.GetMessageClass(pool.FindMessageTypeByName('google.rpc.Status'))
s = Status(code=7, message='permission denied')
detail = wrappers_pb2.StringValue(value='quota')
a = any_pb2.Any(); a.Pack(detail)
s.details.append(a)
data = s.SerializeToString()
print('// Generated by generate_status_details_oracle.py using protobuf 6.33.5.')
print('inline constexpr unsigned char kStatusDetailsOracle[] = {' + ', '.join(f'0x{x:02x}' for x in data) + '};')
print(f'inline constexpr unsigned kStatusDetailsOracleLen = {len(data)};')
print('inline constexpr char kStatusDetailsOracleBase64[] = "' + base64.b64encode(data).decode() + '";')
